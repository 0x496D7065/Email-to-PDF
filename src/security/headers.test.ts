import { describe, expect, it } from 'vitest';
import {
    cloudflareHeadersFile,
    cspForHeader,
    cspForMeta,
    cspForServiceWorker,
    PERMISSIONS_POLICY,
    SERVICE_WORKER_PATH,
    securityHeadersFor,
} from './headers';

// The exact policy documented in README.md, rule R2. If this test fails, the policy
// was changed: loosening it needs the user's explicit approval.
const EXPECTED: Record<string, string> = {
    'default-src': "'none'",
    'script-src': "'self'",
    'style-src': "'self'",
    'img-src': "'self' data: blob:",
    'font-src': "'self'",
    'connect-src': "'none'",
    'worker-src': "'self' blob:",
    'form-action': "'none'",
    'base-uri': "'none'",
    'object-src': "'none'",
    'frame-src': "'none'",
};

/** "a x; b y z" -> { a: "x", b: "y z" } */
function parse(policy: string): Record<string, string>
{
    const result: Record<string, string> = {};
    for (const part of policy.split(';'))
    {
        const [name = '', ...sources] = part.trim().split(/\s+/);
        if (name) result[name] = sources.join(' ');
    }
    return result;
}

describe('Content Security Policy', () =>
{
    it('meta version is exactly the documented policy', () =>
    {
        expect(parse(cspForMeta())).toEqual(EXPECTED);
    });

    it('header version adds only frame-ancestors none', () =>
    {
        expect(parse(cspForHeader())).toEqual({ ...EXPECTED, 'frame-ancestors': "'none'" });
    });

    it('never allows inline code, eval, remote hosts or wildcards', () =>
    {
        for (const policy of [cspForHeader(), cspForMeta()])
        {
            expect(policy).not.toMatch(/unsafe-|http:|https:|\*|nonce-|sha\d+-/);
            // It is written inside a double-quoted HTML attribute.
            expect(policy).not.toContain('"');
        }
    });
});

describe('service worker CSP (/sw.js only)', () =>
{
    it('is the header policy with ONLY connect-src set to self (the user-approved exception)', () =>
    {
        expect(parse(cspForServiceWorker())).toEqual({ ...EXPECTED, 'connect-src': "'self'", 'frame-ancestors': "'none'" });
    });

    it('never allows inline code, eval, remote hosts or wildcards', () =>
    {
        expect(cspForServiceWorker()).not.toMatch(/unsafe-|http:|https:|\*|nonce-|sha\d+-|"/);
    });

    it('is sent with /sw.js only; every other path gets the page policy', () =>
    {
        expect(SERVICE_WORKER_PATH).toBe('/sw.js');
        expect(securityHeadersFor('/sw.js')).toEqual({
            'Content-Security-Policy': cspForServiceWorker(),
            'Referrer-Policy': 'no-referrer',
            'Permissions-Policy': PERMISSIONS_POLICY,
        });
        for (const path of ['/', '/index.html', '/assets/index-abc.js', '/sw.js/', '/assets/sw.js', '/SW.JS', '/sw.json'])
        {
            expect(securityHeadersFor(path), path).toEqual({
                'Content-Security-Policy': cspForHeader(),
                'Referrer-Policy': 'no-referrer',
                'Permissions-Policy': PERMISSIONS_POLICY,
            });
        }
    });
});

describe('_headers file', () =>
{
    it('sends the CSP, referrer and permissions headers for every path', () =>
    {
        const lines = cloudflareHeadersFile().split('\n');
        expect(lines).toContain('/*');
        expect(lines).toContain(`  Content-Security-Policy: ${cspForHeader()}`);
        expect(lines).toContain('  Referrer-Policy: no-referrer');
        expect(lines).toContain(`  Permissions-Policy: ${PERMISSIONS_POLICY}`);
    });

    it('is exactly the /* rule, then a /sw.js rule that detaches the page CSP and sets its own', () =>
    {
        expect(cloudflareHeadersFile().split('\n')).toEqual([
            '# Generated by vite.config.ts from src/security/headers.ts. Do not edit dist/_headers.',
            '/*',
            `  Content-Security-Policy: ${cspForHeader()}`,
            '  Referrer-Policy: no-referrer',
            `  Permissions-Policy: ${PERMISSIONS_POLICY}`,
            '/sw.js',
            '  ! Content-Security-Policy',
            `  Content-Security-Policy: ${cspForServiceWorker()}`,
            '',
        ]);
    });

    it('disables powerful features like camera and geolocation', () =>
    {
        expect(PERMISSIONS_POLICY).toContain('camera=()');
        expect(PERMISSIONS_POLICY).toContain('geolocation=()');
        expect(PERMISSIONS_POLICY).not.toMatch(/\*|self|"/);
    });
});
